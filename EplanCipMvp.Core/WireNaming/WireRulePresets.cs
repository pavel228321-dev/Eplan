using System.Collections.Generic;

namespace EplanCipMvp.Core.WireNaming
{
    /// <summary>
    /// Правила, по которым пронумерованы провода 1260 (выведены из схем PDF 1260, лист 190 и др.;
    /// правила «силовая цепь» и «цепь управления» уточняются по первому живому прогону на копии 1260).
    /// Порядок важен: срабатывает первое подходящее.
    /// </summary>
    public static class WireRulePresets
    {
        public static List<WireRule> Like1260() => new List<WireRule>
        {
            new WireRule { Name = "Защитный провод PE", Terminal = "PE", Template = "PE" },
            // «от первой цифры» — только для устройств «буква участка + 2 цифры» (T32M04), как у кабелей (живой прогон 1364).
            new WireRule { Name = "Главный шкаф → поле (жила)", Location = "+FIELD", Device = "@##@*", OtherLocation = "+CP.E01",
                           Template = "{Устройство:от_цифры}-{Клемма:буквы}" },
            // Только провода «шкаф — поле» (25.09.2026): провода внутри поля (между двумя устройствами +FIELD) не нумеруем,
            // иначе живой прогон 1364 давал K101-2 / WO16-2 на каждом листе и сотни конфликтов.
            new WireRule { Name = "Шкаф → поле (жила)", Location = "+FIELD", OtherLocation = "+CP.*", Template = "{Устройство}-{Клемма:буквы}" },
            // Жилы кабеля пневмоострова: 1260 3VP1-1, 1364 UP1-1 — устройство-клемма, а не номер канала ПЛК.
            new WireRule { Name = "Пневмоостров (жила)", Device = "*VP#;UP#", InCable = "да", Template = "{Устройство}-{Клемма}" },
            // 25.09.2026: провода потенциалов (1M, 31L+, 1L1 — их номер ставит сам EPLAN) эти правила не трогают:
            // Потенциал = «нет». Правила «Потенциал» нет — на 1364 оно записало M/L+/L вместо 1M/30L+/1L1.
            new WireRule { Name = "Канал ПЛК", Device = "*A*.*", Potential = "нет", Template = "{МодульПЛК:цифры}{Клемма:2}" },
            // 01.10.2026: достраивает номер потенциала, когда EPLAN дал только букву (M, L+, L...) без
            // числа — обход вверх до ближайшего автомата/БП (docs/superpowers/specs/2026-10-01-potential-number-generation-design.md).
            new WireRule { Name = "Потенциал (из источника)", Potential = "да",
                           SourceDevice = "??QF*;?QF*;??U*;?U*;??G*;?G*", Template = "{Потенциал:источник}" },
            // Выходы аппаратов группы (1260: 32L41… после автомата, 32L44… после контактора, 32L47… после УПП;
            // у ПЧ л.208 01L11…). Вход автомата от шины — потенциал шины (1L1…), не трогаем.
            new WireRule { Name = "Силовая цепь группы", Device = "??QF*;?QF*;??KM*;??U*", Terminal = "2;4;6;?T?",
                           ExcludeDevice = "*UB*", Potential = "нет", Order = "Y", Template = "{Группа:2}L{Номер:последняя}{Счётчик}" },
            // Сквозной счётчик 1260 (121…): реле, контакты, катушки. Питание модулей ПЛК (1A/M), CPU, Profinet, шины — не цепи управления.
            new WireRule { Name = "Цепь управления", Location = "+CP.*", Potential = "нет", ExcludeDevice = "*A*.*;#A#;*UE*;*UB*",
                           CounterStart = 121, Template = "{Счётчик}" },
        };
    }
}
